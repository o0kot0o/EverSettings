-- Builds docs/COVERAGE.md: database coverage and verification progress, from the same
-- code the addon uses in game (Diagnostics:Coverage). Invoked by run_tests.py --coverage.
local ns = ES_NS
local c = ns.Diagnostics:Coverage()
local Util = ns.Util
local out = {}
local function add(s, ...) out[#out + 1] = select("#", ...) > 0 and s:format(...) or s end

local meta = ns.CVarCatalog.meta
add("# Settings database coverage")
add("")
add("Generated by `python tests/run_tests.py --coverage` from the addon's own data. Do not edit by hand.")
add("")
add("- CVar catalog: **%d** variables and **%d** console commands from client build %s (Ketho/BlizzardInterfaceResources@%s)", meta.numCVars, meta.numCommands, meta.cvarsBuild, meta.cvarsRevision:sub(1, 7))
add("- UI classification: Gethe/wow-ui-source@%s (build %s)", meta.uiRevision:sub(1, 7), meta.uiBuild)
add("- In Blizzard's Forever settings window: **%d**, used by other Blizzard UI: **%d**, hidden: **%d**", c.catalogStandard, c.catalogUi, c.catalogHidden)
add("- Curated definitions: **%d** (%d editable, %d read-only), covering **%d** catalog variables", c.definitions, c.editable, c.readonly, c.catalogClassified)
add("- Unclassified variables (read-only in the CVar browser): **%d**", c.catalogTotal - c.catalogClassified)
add("")
add("## Verification progress")
add("")
add("| Evidence | verified | source | community | experimental | unknown | unsupported |")
add("|---|---|---|---|---|---|---|")
for _, aspect in ipairs(ns.Schema.EvidenceAspects) do
	local e = c.evidence[aspect]
	add("| %s | %d | %d | %d | %d | %d | %d |", ns.Schema.EvidenceLabels[aspect], e.verified or 0, e.source or 0, e.community or 0, e.experimental or 0, e.unknown or 0, e.unsupported or 0)
end
add("")
local verified = {}
for _, d in ipairs(ns.Registry.ordered) do
	if d.provider ~= "diagnostic" and d.verification.effect == "verified" then verified[#verified + 1] = d.name end
end
if #verified == 0 then
	add("No setting has an in-game verified effect yet.")
else
	add("Settings with an in-game verified effect: %s.", table.concat(verified, ", "))
end
add("")
add("## Definitions by category")
add("")
for _, cat in ipairs(ns.Categories.list) do
	local sections = ns.Registry:GetCategorySections(cat.id)
	if #sections > 0 then
		add("### %s", cat.name)
		add("")
		add("| Setting | Technical | Control | Provider | Status | Class | Apply |")
		add("|---|---|---|---|---|---|---|")
		for _, s in ipairs(sections) do
			for _, d in ipairs(s.defs) do
				add("| %s | `%s` | %s | %s | %s | %s | %s |", d.name, d.technical, d.control, d.provider, d.statusSummary, d.classification, d.apply)
			end
		end
		add("")
	else
		add("### %s", cat.name)
		add("")
		add("No researched settings yet.")
		add("")
	end
end
return table.concat(out, "\n") .. "\n"
