local _, ns = ...
local Changes, Providers = ns.Changes, ns.Providers

describe("staging", function()
	it("stages without touching the game", function()
		Changes:Stage(def("graphics.gamma"), 1.5)
		eq(Changes:Count(), 1)
		eq(writes(), 0)
		eq(raw("Gamma"), "1.000000")
		eq(Changes:GetEffective(def("graphics.gamma")), 1.5)
	end)
	it("drops a pending change that equals the current value", function()
		local d = def("graphics.gamma")
		Changes:Stage(d, 1.5)
		Changes:Stage(d, 1.0)
		eq(Changes:Count(), 0)
	end)
	it("refuses to stage read-only settings", function()
		falsy(Changes:Stage(def("graphics.farclip"), 2000))
		eq(Changes:Count(), 0)
	end)
	it("stages category defaults only where values differ", function()
		MOCK.cvars.gamma = "2"
		MOCK.cvars.autolootdefault = "1"
		local n = Changes:StageCategoryDefaults("graphics")
		eq(n, 1)
		near(Changes.pending["graphics.gamma"], 1)
		eq(Changes.pending["qol.autoLoot"], nil)
		eq(writes(), 0)
	end)
end)

describe("apply pipeline", function()
	it("writes, reads back and reports success", function()
		Changes:Stage(def("graphics.gamma"), 1.25)
		local report = Changes:ApplyAll()
		eq(report.counts.success, 1)
		eq(raw("Gamma"), "1.25")
		eq(Changes:Count(), 0)
		eq(#ns.db.history, 1)
		eq(ns.db.history[1].source, "apply")
	end)
	it("records the original value only the first time", function()
		local d = def("graphics.gamma")
		Changes:Stage(d, 1.25); Changes:ApplyAll()
		Changes:Stage(d, 1.5); Changes:ApplyAll()
		near(ns.Backup:GetOriginal(d), 1.0)
	end)
	it("detects values clamped by the client", function()
		MOCK.clamp.gamma = function() return "2" end
		Changes:Stage(def("graphics.gamma"), 2.5)
		local report = Changes:ApplyAll()
		eq(report.counts.clamped, 1)
		eq(report.results[1].status, "clamped")
		near(report.results[1].after, 2)
	end)
	it("detects silently rejected writes", function()
		MOCK.reject.gamma = true
		Changes:Stage(def("graphics.gamma"), 2.5)
		local report = Changes:ApplyAll()
		eq(report.counts.rejected, 1)
		eq(raw("Gamma"), "1.000000")
	end)
	it("keeps secure settings pending during combat and never writes them", function()
		local d = def("qol.autoStand")
		Changes:Stage(d, false)
		MOCK.combat = true
		local report = Changes:ApplyAll()
		eq(report.counts.restricted, 1)
		eq(writes("autoStand"), 0)
		eq(Changes:Count(), 1, "still pending")
		MOCK.combat = false
		report = Changes:ApplyAll()
		eq(report.counts.success, 1)
		eq(raw("autoStand"), "0")
	end)
	it("treats read-only client variables as restricted", function()
		MOCK.readOnly.gamma = true
		Changes:Stage(def("graphics.gamma"), 2)
		eq(Changes:ApplyAll().counts.restricted, 1)
	end)
	it("rejects invalid staged values without writing", function()
		Changes.pending["graphics.gamma"] = 99
		local report = Changes:ApplyAll()
		eq(report.counts.failed, 1)
		eq(writes(), 0)
	end)
	it("warns about unmet dependencies", function()
		Changes:Stage(def("graphics.uiScale"), 0.8) -- useUiScale defaults to 0
		local report = Changes:ApplyAll()
		eq(report.counts.success, 1)
		truthy(report.results[1].warnings and #report.results[1].warnings == 1)
	end)
	it("reports restart requirements", function()
		Changes:Stage(def("graphics.physicsLevel"), 2)
		local report = Changes:ApplyAll()
		contains(report.notices, "restart")
		truthy(Changes:FormatReport(report):find("restart"))
	end)
end)

describe("composite settings", function()
	it("mouse look speed sets pitch to half of yaw", function()
		Changes:Stage(def("camera.mouseLookSpeed"), 200)
		Changes:ApplyAll()
		eq(raw("cameraYawMoveSpeed"), "200")
		eq(raw("cameraPitchMoveSpeed"), "100")
	end)
	it("triple buffering maps to gxMaxFrameLatency 3/2", function()
		local d = def("graphics.tripleBuffering")
		eq(Providers:Get(d), true)
		Changes:Stage(d, false); Changes:ApplyAll()
		eq(raw("GxMaxFrameLatency"), "2")
	end)
	it("camera shake sets both strengths", function()
		Changes:Stage(def("camera.shake"), 0.25); Changes:ApplyAll()
		eq(raw("ShakeStrengthCamera"), "0.25")
		eq(raw("ShakeStrengthUI"), "0.25")
	end)
	it("graphics preset cascades to supported children, respecting minimums", function()
		Changes:Stage(def("graphics.qualityPreset"), 0)
		Changes:ApplyAll()
		eq(raw("graphicsQuality"), "0")
		eq(raw("graphicsShadowQuality"), "0")
		eq(raw("graphicsParticleDensity"), "1", "particle density minimum 1")
		eq(raw("graphicsPBRLiquidDetail"), "1", "unsupported PBR child left alone")
	end)
	it("applies the preset before individually staged quality settings", function()
		Changes:Stage(def("graphics.qualityPreset"), 0)
		Changes:Stage(def("graphics.shadowQuality"), 5)
		Changes:ApplyAll()
		eq(raw("graphicsShadowQuality"), "5", "explicit choice wins over preset")
	end)
	it("API provider toggles minimap trivial quest tracking", function()
		local d = def("questing.trivialQuests")
		eq(Providers:Get(d), false)
		Changes:Stage(d, true); Changes:ApplyAll()
		eq(Providers:Get(d), true)
	end)
end)

describe("undo and redo", function()
	it("undoes and redoes an apply", function()
		Changes:Stage(def("graphics.gamma"), 1.5)
		Changes:Stage(def("qol.autoLoot"), true)
		Changes:ApplyAll()
		truthy(ns.History:CanUndo())
		ns.History:Undo()
		eq(raw("Gamma"), "1.000000", "undo restores the exact original raw string")
		eq(raw("autoLootDefault"), "0")
		truthy(ns.History:CanRedo())
		ns.History:Redo()
		eq(raw("Gamma"), "1.5")
		eq(raw("autoLootDefault"), "1")
	end)
end)
