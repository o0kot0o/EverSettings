local _, ns = ...
local Values = ns.Values

describe("input parsing", function()
	it("accepts plain, decimal and exponent numbers", function()
		eq(ns.Util.ParseNumber("12"), 12)
		eq(ns.Util.ParseNumber("-3.5"), -3.5)
		eq(ns.Util.ParseNumber(".5"), 0.5)
		eq(ns.Util.ParseNumber("1e2"), 100)
		eq(ns.Util.ParseNumber(" 7 "), 7)
		eq(ns.Util.ParseNumber("1,5"), 1.5)
	end)
	it("rejects garbage", function()
		eq(ns.Util.ParseNumber(""), nil)
		eq(ns.Util.ParseNumber("abc"), nil)
		eq(ns.Util.ParseNumber("12abc"), nil)
		eq(ns.Util.ParseNumber("1.2.3"), nil)
		eq(ns.Util.ParseNumber("nan"), nil)
		eq(ns.Util.ParseNumber("inf"), nil)
	end)
end)

describe("numeric values", function()
	it("keeps exactly typed values instead of rounding to the slider step", function()
		local d = def("graphics.gamma") -- step 0.1
		local v = Values.ParseInput(d, "1.23")
		near(v, 1.23)
		truthy(Values.Validate(d, v))
		eq(Values.FormatNumber(d, v), "1.23")
	end)
	it("rejects values outside the researched range", function()
		local d = def("graphics.gamma")
		falsy(Values.Validate(d, 2.9))
		falsy(Values.Validate(d, 0.2))
		truthy(Values.Validate(d, 2.8))
		truthy(Values.Validate(d, 0.3))
	end)
	it("rejects fractions for integer settings", function()
		local d = def("performance.maxFPS")
		local v, err = Values.ParseInput(d, "60.5")
		eq(v, nil)
		truthy(err)
		eq(Values.ParseInput(d, "60 fps"), 60)
	end)
	it("converts percentage display values", function()
		local d = def("graphics.uiScale")
		near(Values.ParseInput(d, "65"), 0.65)
		near(Values.ParseInput(d, "80%"), 0.8)
		eq(Values.Format(d, 0.65), "65%")
		falsy(Values.Validate(d, Values.ParseInput(d, "150")))
	end)
	it("shows quality levels 1-10 for stored values 0-9", function()
		local d = def("graphics.viewDistance")
		eq(Values.Format(d, 0), "1")
		eq(Values.Format(d, 9), "10")
		eq(Values.ParseInput(d, "10"), 9)
		falsy(Values.Validate(d, Values.ParseInput(d, "11")))
	end)
	it("uses runtime ranges from the client", function()
		local d = def("camera.fov")
		local lo, hi = ns.Providers:GetRange(d)
		eq(lo, 50); eq(hi, 90)
		falsy(Values.Validate(d, 95))
	end)
end)

describe("boolean and enum values", function()
	it("reads and writes booleans, honouring inverted storage", function()
		local d = def("qol.stickyTargeting") -- deselectOnClick, inverted
		eq(Values.FromRaw(d, "0"), true)
		eq(Values.FromRaw(d, "1"), false)
		eq(Values.ToRaw(d, true), "0")
	end)
	it("validates enums against documented options only", function()
		local d = def("graphics.textureFiltering")
		truthy(Values.Validate(d, 5))
		falsy(Values.Validate(d, 6))
		eq(Values.Format(d, 3), "4x Anisotropic")
		eq(Values.Format(d, 9), "9 (undocumented)")
	end)
	it("supports string enums", function()
		local d = def("interface.whisperMode")
		eq(Values.FromRaw(d, "popout"), "popout")
		truthy(Values.Validate(d, "popout_and_inline"))
		falsy(Values.Validate(d, "sideways"))
	end)
	it("disables options the system reports as unsupported", function()
		local d = def("performance.lowLatencyMode")
		local reflex
		for _, o in ipairs(ns.Providers:GetOptions(d)) do if o.value == 3 then reflex = o end end
		truthy(reflex.disabled, "Reflex unsupported in mock")
		falsy(Values.Validate(d, 3))
		truthy(Values.Validate(d, 1))
	end)
	it("labels camera shake values set elsewhere as custom and refuses to select it", function()
		local d = def("camera.shake")
		MOCK.cvars.shakestrengthcamera = "0.5"
		eq(ns.Providers:Get(d), "custom")
		eq(Values.Format(d, "custom"), "Custom (set elsewhere)")
		falsy(Values.Validate(d, "custom"))
	end)
end)
